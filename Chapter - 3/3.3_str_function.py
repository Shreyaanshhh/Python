name = "Shreyansh Pandey"

print("1) Length of the string:", len(name))
print("2) Ends with 'dey':", name.endswith("dey"))
print("3) Starts with 'Sh':", name.startswith("Sh"))
print("4) Capitalized:", name.capitalize())
print("5) Upper case:", name.upper())
print("6) Lower case:", name.lower())
print("7) Title case:", name.title())
print("8) Find 'n':", name.find("n"))
print("9) Count 'a':", name.count("a"))
print("10) Replace 'Shreyansh' with 'Mukesh':", name.replace("Shreyansh", "Mukesh"))
print("11) Is alpha:", name.isalpha())
print("12) Is alphanumeric:", name.isalnum())
print("13) Is digit:", name.isdigit())
print("14) Is space:", name.isspace())
print("15) Is lower:", name.islower())
print("16) Is upper:", name.isupper())
print("17) Swap case:", name.swapcase())
print("18) Center:", name.center(20))
print("19) Strip:", name.strip())
print("20) Left strip:", name.lstrip())
print("21) Right strip:", name.rstrip())
print("22) Split:", name.split())
print("23) Partition:", name.partition("r"))
print("24) Index:", name.index("r"))